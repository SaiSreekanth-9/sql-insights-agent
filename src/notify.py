"""Mock notification renderers — drafts only, nothing is ever sent.

These functions build the exact text that *would* be delivered by email or
Slack, so the notification layer can be reviewed and tested without any
SMTP server, Slack token, or network call. Wiring a real sender up later
means calling these renderers and passing their output to the real client.
"""


def render_draft_email(insights: list, period: str = "") -> dict:
    """Return a draft email as ``{"subject": ..., "body": ...}``."""
    subject = "📊 Daily metrics insights" + (f" — {period}" if period else "")
    lines = [
        "Hi team,",
        "",
        "Here are the automated insights from the latest metrics run"
        + (f" ({period})" if period else "")
        + ":",
        "",
    ]
    for insight in insights:
        lines.append(f"• {insight}")
    lines += [
        "",
        "Full details are in the attached report.",
        "",
        "— sql-insights-agent (automated, do not reply)",
    ]
    return {"subject": subject, "body": "\n".join(lines)}


def render_slack_message(insights: list, period: str = "") -> str:
    """Return a Slack-style markdown message (no API call)."""
    header = ":bar_chart: *Daily metrics insights*" + (
        f" — {period}" if period else ""
    )
    blocks = [header, ""]
    for insight in insights:
        blocks.append(f"• {insight}")
    blocks.append("")
    blocks.append("_Generated by sql-insights-agent · demo mode, nothing was sent._")
    return "\n".join(blocks)
